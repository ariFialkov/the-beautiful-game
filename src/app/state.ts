import type { ServerConfigPublic, Wallet } from '@shared/types';
import type { CamStyle } from '../render/camera';
import type { ControlPrefs } from '../game/match';
import { normalizeTactics, type Tactics } from '../game/tactics';

export interface Settings {
  sound: boolean;
  quality: 'auto' | 'low' | 'high';
  cameraHeight: number; // 0.6..1.6 multiplier
  showTouch: 'auto' | 'on' | 'off';
  vibration: boolean;
  /** Match camera for 11-a-side games, and for futsal. */
  camera: CamStyle;
  cameraFutsal: CamStyle;
  /** Controller assistance and player switching. */
  controls: ControlPrefs;
}

type Listener = () => void;

class AppState {
  config: ServerConfigPublic | null = null;
  wallet: Wallet | null = null;
  nextServerSeedHash = '';
  settings: Settings = { sound: true, quality: 'auto', cameraHeight: 1, showTouch: 'auto', vibration: true, camera: 'tele', cameraFutsal: 'end', controls: { pass: 'assisted', shot: 'assisted', switching: 'auto' } };
  homeTeamId = 'lon-royals';
  awayTeamId = 'mad-blancos';
  stake = 50;
  /** Match conditions preference: 'random' or a surface id. */
  conditions = 'random';
  /** Your formation and team instructions: one set for 11-a-side, one for futsal. */
  tactics: Tactics = normalizeTactics(undefined, false);
  tacticsFutsal: Tactics = normalizeTactics(undefined, true);
  offline = false;
  /** True when outcomes are generated by the in-browser engine (static hosting / offline demo). */
  local = false;
  private listeners = new Set<Listener>();

  constructor() {
    try { const s = localStorage.getItem('tbg.settings'); if (s) { const o = JSON.parse(s); this.settings = { ...this.settings, ...o, controls: { ...this.settings.controls, ...(o.controls ?? {}) } }; } } catch { /* ignore */ }
    try { const t = localStorage.getItem('tbg.tactics'); if (t) { const o = JSON.parse(t); this.tactics = normalizeTactics(o.full, false); this.tacticsFutsal = normalizeTactics(o.futsal, true); } } catch { /* ignore */ }
    try { const t = localStorage.getItem('tbg.teams'); if (t) { const o = JSON.parse(t); this.homeTeamId = o.home ?? this.homeTeamId; this.awayTeamId = o.away ?? this.awayTeamId; this.stake = o.stake ?? this.stake; this.conditions = o.conditions ?? this.conditions; } } catch { /* ignore */ }
  }
  subscribe(fn: Listener) { this.listeners.add(fn); return () => this.listeners.delete(fn); }
  emit() { for (const l of this.listeners) l(); }
  setWallet(w: Wallet) { this.wallet = w; this.emit(); }
  saveSettings(patch: Partial<Settings>) { this.settings = { ...this.settings, ...patch }; localStorage.setItem('tbg.settings', JSON.stringify(this.settings)); this.emit(); }
  tacticsFor(futsal: boolean) { return futsal ? this.tacticsFutsal : this.tactics; }
  saveTactics(futsal: boolean, t: Partial<Tactics>) {
    if (futsal) this.tacticsFutsal = normalizeTactics({ ...this.tacticsFutsal, ...t }, true); else this.tactics = normalizeTactics({ ...this.tactics, ...t }, false);
    try { localStorage.setItem('tbg.tactics', JSON.stringify({ full: this.tactics, futsal: this.tacticsFutsal })); } catch { /* (storage blocked) */ }
  }
  saveTeams() { localStorage.setItem('tbg.teams', JSON.stringify({ home: this.homeTeamId, away: this.awayTeamId, stake: this.stake, conditions: this.conditions })); }
}

export const state = new AppState();
export const isTouchDevice = () => matchMedia('(pointer: coarse)').matches || 'ontouchstart' in window;
export const fmt = (n: number) => n.toLocaleString(undefined, { maximumFractionDigits: 0 });
